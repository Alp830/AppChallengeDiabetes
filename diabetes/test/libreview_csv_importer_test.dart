import 'package:diabetes/cgm/data/demo_cgm_importer.dart';
import 'package:diabetes/cgm/data/libreview_csv_importer.dart';
import 'package:diabetes/cgm/models/glucose_models.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('parses comma-delimited mg/dL LibreView data and removes duplicates', () async {
    const csv = '''Generated by LibreView
Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL
Libre 3,ABC,7/12/2026 9:15 AM,0,123,
Libre 3,ABC,7/12/2026 9:15 AM,0,123,
Libre 3,ABC,7/12/2026 9:30 AM,1,,130
''';
    final preview = await const LibreViewCsvImporter().parse(csv);

    expect(preview.readings, hasLength(2));
    expect(preview.duplicateRows, 1);
    expect(preview.detectedUnit, 'mg/dL');
    expect(preview.readings.first.recordType, GlucoseRecordType.historic);
    expect(preview.timezoneWasInferred, isFalse);
  });

  test('parses semicolon-delimited European mmol/L data', () async {
    const csv = '''Device;Serial Number;Device Timestamp;Record Type;Historic Glucose mmol/L;Scan Glucose mmol/L
Libre;XYZ;13/07/2026 09:15;0;6,5;
Libre;XYZ;13/07/2026 09:30;0;7,0;
''';
    final preview = await const LibreViewCsvImporter().parse(csv);

    expect(preview.readings, hasLength(2));
    expect(preview.readings.first.timestamp.month, 7);
    expect(preview.readings.first.timestamp.day, 13);
    expect(preview.readings.first.valueMgDl, closeTo(117.1, .2));
  });

  test('rejects unsupported files', () async {
    expect(
      () => const LibreViewCsvImporter().parse('name,value\nfoo,1'),
      throwsA(isA<FormatException>()),
    );
  });

  test('demo importer produces isolated deterministic readings', () async {
    final preview = await const DemoCgmImporter(days: 2).parse('');
    expect(preview.readings, hasLength(192));
    expect(preview.source, GlucoseSource.demo);
    expect(preview.readings.every((item) => item.source == GlucoseSource.demo), isTrue);
  });
}
